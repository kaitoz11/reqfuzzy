// Optional browser acceptance. Build .reqfuzzy/bin/reqfuzzy and install Playwright
// into .reqfuzzy/browser first; no Node dependency is needed to run reqfuzzy.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.resolve(process.env.REQFUZZY_PLAYWRIGHT_PACKAGE || path.join(root, '.reqfuzzy/browser/package.json')));
const { chromium } = require('playwright');
const binary = process.env.REQFUZZY_BIN || path.join(root, '.reqfuzzy/bin/reqfuzzy');
await fs.mkdir(path.join(root, '.reqfuzzy'), { recursive: true, mode: 0o700 });
const artifacts = await fs.mkdtemp(path.join(root, '.reqfuzzy/flow-map-browser-'));
const cli = (...args) => JSON.parse(execFileSync(binary, [...args, '--json'], { cwd: root, encoding: 'utf8' }));
const reference = path.join(root, 'examples/stateful-tests');
const referenceMap = path.join(artifacts, 'reference.html');
const juiceMap = path.join(artifacts, 'juice-shop.html');
cli('flow', 'map', '--project', reference, '--test', 'tests.yaml', '--out', referenceMap);
cli('flow', 'map', '--project', path.join(root, 'examples/juice-shop'), '--test', 'tests.yaml', '--out', juiceMap);

const browser = await chromium.launch({ headless: true, executablePath: process.env.REQFUZZY_BROWSER || undefined });
try {
  const context = await browser.newContext({ viewport: { width: 1560, height: 1000 }, acceptDownloads: true, offline: true });
  const page = await context.newPage();
  const errors = [], network = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith('file:') && !request.url().startsWith('blob:')) network.push(request.url()); });
  const field = key => page.locator(`[data-focus="${key}"]`);
  const node = (phase, id) => page.getByRole('button', { name: `Select ${phase} step ${id}`, exact: true });
  const sectionAdd = title => page.locator('.section-title').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).getByRole('button', { name: 'Add', exact: true });
  const isExportable = async () => !(await page.locator('#download').isDisabled());
  await page.goto(pathToFileURL(referenceMap).href);
  await page.waitForSelector('g.node');
  assert.equal(await page.locator('g.node').count(), 4);
  assert.equal(await page.locator('g.edge').count(), 7);
  assert.equal(await isExportable(), true);
  await node('Journey', 'session').focus();
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('.inspector-head h2').innerText(), 'nonce');
  await node('Journey', 'transfer').click();
  await page.getByRole('button', { name: 'Move up', exact: true }).click();
  assert.equal(await isExportable(), false, 'forward nonce reference must block export');
  await page.locator('#undo').click();
  assert.equal(await isExportable(), true);
  await node('Journey', 'session').click();
  await sectionAdd('Response extractions').click();
  await field('flow:0-extract-4-source').selectOption('cookie');
  assert.equal(await field('flow:0-extract-4-source').inputValue(), 'cookie', 'empty cookie extraction must retain its source kind');
  await field('flow:0-extract-4-name').fill('cookie2');
  await field('flow:0-extract-4-selector').fill('session2');
  assert.equal(await isExportable(), true);
  await field('flow:0-extract-4-selector').fill('');
  assert.equal(await field('flow:0-extract-4-source').inputValue(), 'cookie', 'clearing a cookie selector must keep the draft type');
  assert.equal(await isExportable(), false);
  await page.getByRole('button', { name: 'Remove extraction', exact: true }).last().click();
  assert.equal(await isExportable(), true);
  await field('flow:0-extract-2-name').fill('renamed_balance');
  assert.equal(await isExportable(), false, 'campaign variable reference must remain valid');
  await page.locator('#undo').click();
  await node('Journey', 'transfer').click();
  await field('flow:2-id').fill('renamed_transfer');
  assert.equal(await isExportable(), false, 'campaign target/check steps must remain valid');
  await page.locator('#undo').click();
  assert.equal(await isExportable(), true);

  await page.locator('#add-step').click();
  await field('flow:3-id').fill('read-again');
  await field('flow:3-request').selectOption('balance');
  await field('flow:3-status').fill('200');
  await sectionAdd('Request bindings').click();
  assert.equal(await isExportable(), false, 'empty binding address must block export');
  await field('flow:3-bind-0-location').selectOption('header');
  await field('flow:3-bind-0-path').fill('Authorization');
  await field('flow:3-bind-0-variable').selectOption('token');
  await field('flow:3-bind-0-prefix').fill('Bearer ');
  await sectionAdd('Request bindings').click();
  await field('flow:3-bind-1-location').selectOption('cookie');
  await field('flow:3-bind-1-path').fill('reference_sid');
  await field('flow:3-bind-1-variable').selectOption('sid');
  assert.equal(await isExportable(), true);
  assert.equal(await page.locator('g.node').count(), 5);
  assert.equal(await page.locator('g.edge').count(), 9);
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#download').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'flow.yaml');
  const exported = path.join(artifacts, 'edited-flow.yaml');
  await download.saveAs(exported);
  const definition = JSON.parse(await fs.readFile(exported, 'utf8'));
  assert.equal(definition.steps[3].id, 'read-again');
  assert.equal(definition.steps[3].expect_status, 200);
  assert.equal(definition.steps[3].bind[0].prefix, 'Bearer ');
  assert.equal(definition.steps[3].bind[1].location, 'cookie');
  const editedProject = path.join(artifacts, 'edited-project');
  await fs.cp(reference, editedProject, { recursive: true });
  await fs.copyFile(exported, path.join(editedProject, 'flow.yaml'));
  assert.equal(cli('flow', 'show', '--project', editedProject).result.steps.length, 4);
  cli('flow', 'map', '--project', editedProject, '--test', 'tests.yaml', '--out', path.join(artifacts, 'roundtrip.html'));
  await page.getByRole('button', { name: 'Verification', exact: true }).click();
  assert.equal(await page.locator('.inspector-head h2').innerText(), 'balance');
  assert.ok(await page.locator('#canvas').evaluate(element => element.scrollTop) > 0, 'phase selection reveals verification node');

  await page.goto(pathToFileURL(juiceMap).href);
  await page.waitForSelector('g.node');
  assert.equal(await page.locator('g.node').count(), 6);
  assert.equal(await page.locator('g.edge').count(), 8);
  await node('Journey', 'update').click();
  await page.locator('#location').selectOption('path');
  await page.screenshot({ path: path.join(artifacts, 'juice-shop-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#fit').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'narrow view has no document overflow');
  await page.screenshot({ path: path.join(artifacts, 'juice-shop-narrow.png'), fullPage: true });

  const payload = JSON.parse((await fs.readFile(referenceMap, 'utf8')).match(/<script id="project-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
  const hostileProject = path.join(artifacts, 'hostile-project');
  await fs.cp(reference, hostileProject, { recursive: true });
  payload.flows[0].definition.name = '</script><img src=x onerror="globalThis.injected=true">';
  await fs.writeFile(path.join(hostileProject, 'flow.yaml'), JSON.stringify(payload.flows[0].definition));
  const hostileMap = path.join(artifacts, 'hostile.html');
  cli('flow', 'map', '--project', hostileProject, '--out', hostileMap);
  await page.goto(pathToFileURL(hostileMap).href);
  await page.waitForSelector('g.node');
  assert.equal(await page.locator('#project-title').innerText(), payload.flows[0].definition.name);
  assert.equal(await page.locator('img').count(), 0);
  assert.equal(await page.evaluate(() => globalThis.injected), undefined);
  assert.equal(await page.locator('#campaign').isVisible(), false);
  assert.deepEqual(errors, []);
  assert.deepEqual(network, []);
  console.log(JSON.stringify({ artifacts, browser: 'pass', exportedMainSteps: definition.steps.length, networkRequests: network.length }));
  await context.close();
} finally { await browser.close(); }
